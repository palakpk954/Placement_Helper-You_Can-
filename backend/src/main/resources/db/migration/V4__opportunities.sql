CREATE TABLE opportunities (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(255) NOT NULL,
    organization VARCHAR(255) NOT NULL,
    type VARCHAR(50) NOT NULL,
    category VARCHAR(100) DEFAULT 'Technology',
    mode VARCHAR(50) DEFAULT 'Remote',
    location VARCHAR(255),
    compensation_or_prize VARCHAR(255) NOT NULL,
    eligible_batches VARCHAR(255) DEFAULT 'All Batches',
    eligible_branches VARCHAR(255) DEFAULT 'All Branches',
    deadline TIMESTAMP NOT NULL,
    event_date DATE,
    registration_url VARCHAR(1000) NOT NULL,
    description TEXT,
    perks VARCHAR(500),
    featured BOOLEAN DEFAULT FALSE,
    active BOOLEAN DEFAULT TRUE,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_opportunities_type ON opportunities(type);
CREATE INDEX idx_opportunities_active ON opportunities(active);
CREATE INDEX idx_opportunities_deadline ON opportunities(deadline);

