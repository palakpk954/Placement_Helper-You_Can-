CREATE TABLE job_applications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    upcoming_drive_id BIGINT REFERENCES upcoming_drives(id) ON DELETE SET NULL,
    company_id BIGINT REFERENCES companies(id) ON DELETE SET NULL,
    company_name VARCHAR(150) NOT NULL,
    role_title VARCHAR(150) NOT NULL,
    ctc_or_stipend VARCHAR(100),
    application_type VARCHAR(30) NOT NULL DEFAULT 'ON_CAMPUS',
    stage VARCHAR(50) NOT NULL DEFAULT 'APPLIED',
    applied_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    next_event_date TIMESTAMP,
    next_event_title VARCHAR(150),
    interview_location VARCHAR(150),
    notes TEXT,
    rating INT DEFAULT 0,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_job_app_user ON job_applications(user_id);
CREATE INDEX idx_job_app_stage ON job_applications(user_id, stage);
CREATE INDEX idx_job_app_drive ON job_applications(upcoming_drive_id);

-- Backfill from existing drive_registrations
INSERT INTO job_applications (
    user_id, upcoming_drive_id, company_id, company_name, role_title, ctc_or_stipend,
    application_type, stage, applied_at, notes, created_at, updated_at
)
SELECT 
    dr.user_id,
    dr.upcoming_drive_id,
    ud.company_id,
    ud.company_name,
    ud.roles_offered,
    ud.ctc_or_stipend,
    'ON_CAMPUS',
    CASE 
        WHEN dr.status = 'WITHDRAWN' THEN 'REJECTED'
        ELSE 'APPLIED'
    END,
    COALESCE(dr.registered_at, CURRENT_TIMESTAMP),
    dr.notes,
    COALESCE(dr.registered_at, CURRENT_TIMESTAMP),
    CURRENT_TIMESTAMP
FROM drive_registrations dr
JOIN upcoming_drives ud ON dr.upcoming_drive_id = ud.id;

